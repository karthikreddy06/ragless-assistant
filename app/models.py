from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, field_validator, model_validator


class AskRequest(BaseModel):
    """Incoming user question payload."""

    question: str = Field(
        ...,
        min_length=1,
        max_length=500,
        description="Natural-language question about the organization",
        examples=["How many days of annual leave do employees get?"],
    )

    @field_validator("question")
    @classmethod
    def clean_question(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("Question cannot be empty or solely whitespace.")
        return trimmed


class AskResponse(BaseModel):
    """Response payload containing generated answer and deterministic retrieval metadata."""

    question: str = Field(..., description="The original question submitted by the user")
    answer: str = Field(..., description="Natural-language grounded answer generated by the local LLM")
    source: str = Field(default="sqlite", description="Source of truth for retrieved structured facts")
    intent: Optional[str] = Field(default=None, description="Classified intent (e.g. leave_policy, company_info, multi_query)")
    query_type: Optional[str] = Field(default=None, description="Specific query type mapped for retrieval")
    retrieved_data: Optional[Any] = Field(default=None, description="Structured data retrieved from SQLite")
    processing_time_ms: Optional[float] = Field(default=None, description="Total pipeline execution time in milliseconds")
    queries_executed: Optional[int] = Field(default=None, description="Count of retrieval operations executed")


