class KnowledgePayload(BaseModel):
    """Full schema validation for uploaded knowledge JSON payloads."""

    company: CompanyKnowledgeModel
    departments: List[DepartmentKnowledgeModel] = Field(
        default_factory=list, description="List of company departments and headcounts"
    )
    leave_policy: List[LeavePolicyKnowledgeModel] = Field(
        default_factory=list, description="List of leave policy rules and day counts"
    )
    onboarding_items: List[OnboardingItemKnowledgeModel] = Field(
        default_factory=list, description="List of onboarding checklist items"
    )

    @model_validator(mode="after")
    def validate_unique_entries(self):
        # 1. Check for duplicate department names (case-insensitive)
        dept_seen = set()
        for d in self.departments:
            norm_name = d.name.strip().lower()
            if norm_name in dept_seen:
                raise ValueError(f"Duplicate department name detected: '{d.name}'")
            dept_seen.add(norm_name)

        # 2. Check for duplicate leave types (case-insensitive)
        leave_seen = set()
        for l in self.leave_policy:
            norm_leave = l.leave_type.strip().lower()
            if norm_leave in leave_seen:
                raise ValueError(f"Duplicate leave policy type detected: '{l.leave_type}'")
            leave_seen.add(norm_leave)

        return self


