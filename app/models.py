import re

ALLOWED_INTENTS = {"company_info", "department_employees", "leave_policy", "onboarding", "unknown"}

ALLOWED_QUERY_TYPES = {
    # company operations
    "company_name", "company_location", "company_employees", "all_company",
    "name", "location", "employees",
    # department operations
    "dept_headcount", "all_depts", "total_dept_headcount", "department_employees",
    # leave operations
    "leave_days", "all_leaves", "leave_policy",
    # onboarding operations
    "onboarding_checklist", "onboarding_items", "all_onboarding",
    # unknown
    "unknown"
}

FORBIDDEN_SQL_PATTERNS = [
    r";", r"--", r"/\*", r"\*/",
    r"\bselect\b", r"\binsert\b", r"\bupdate\b", r"\bdelete\b",
    r"\bdrop\b", r"\balter\b", r"\btruncate\b", r"\bunion\b",
    r"\bexec\b", r"\bexecute\b",
]


class QueryOperation(BaseModel):
    """
    Validated single retrieval operation.
    Strictly forbids raw SQL fields or malicious SQL constructs.
    """

    model_config = {"extra": "forbid"}

    intent: str = Field(..., description="Target database domain/intent")
    query_type: str = Field(..., description="Predefined query operation identifier")
    entity: Optional[str] = Field(default=None, max_length=100, description="Optional entity or key filter")

    @field_validator("intent")
    @classmethod
    def validate_intent(cls, v: str) -> str:
        s = v.strip().lower()
        if s not in ALLOWED_INTENTS:
            raise ValueError(f"Disallowed intent '{v}'. Must be one of {sorted(ALLOWED_INTENTS)}")
        return s

    @field_validator("query_type")
    @classmethod
    def validate_query_type(cls, v: str) -> str:
        s = v.strip().lower()
        if s not in ALLOWED_QUERY_TYPES:
            raise ValueError(f"Disallowed query_type '{v}'. Must be one of {sorted(ALLOWED_QUERY_TYPES)}")
        return s

    @field_validator("entity")
    @classmethod
    def sanitize_entity(cls, v: Optional[str]) -> Optional[str]:
        if v is None:
            return None
        s = v.strip()
        if not s or s.lower() in ("null", "none"):
            return None
        s_lower = s.lower()
        for pat in FORBIDDEN_SQL_PATTERNS:
            if re.search(pat, s_lower):
                raise ValueError(f"Forbidden SQL syntax or punctuation detected in entity: '{v}'")
        return s


class QueryPlan(BaseModel):
    """
    Structured query plan specifying 1 to 5 predefined retrieval operations.
    Strictly forbids SQL generation or uncontrolled execution.
    """

    model_config = {"extra": "forbid"}

    queries: List[QueryOperation] = Field(
        ...,
        min_length=1,
        max_length=5,
        description="List of 1 to 5 predefined retrieval operations",
    )


