class CompanyKnowledgeModel(BaseModel):
    """Validation schema for company details in knowledge imports."""

    name: str = Field(..., min_length=1, max_length=150, description="Company name")
    location: str = Field(..., min_length=1, max_length=150, description="Company headquarters or primary city")
    employees: int = Field(..., gt=0, description="Total company headcount (must be greater than 0)")

    @field_validator("name", "location")
    @classmethod
    def not_empty_str(cls, v: str) -> str:
        s = v.strip()
        if not s:
            raise ValueError("Field cannot be empty or solely whitespace.")
        return s


